-- ============================================================
-- a 表：回流用户 + 回流日期 + 斯诺克标记
-- ============================================================
user_info as (
  select distinct
    h.dt,
    h.user_ukey,
    case when s.user_ukey is not null then 1 else 0 end as is_overlap
  from huiliu_user h
  left join sport_top_user s
    on h.user_ukey = s.user_ukey
)

select 
  dt,
  count(distinct user_ukey) as user_cnt
from user_info 
where is_overlap = 1
group by dt