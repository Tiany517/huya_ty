-- 主播日明细：先在独立 CTE 里完成分区时间 + 业务条件过滤（不掺主播名单）
anchor_day_raw as (
    select
        dt,
        cast(ayyuid as varchar) as luid,
        nickname,
        live_hours_only_live
    from gamelive.dm_huya_ayyuid_detail_day
    where dt between '2026-09-01' and '2026-09-30'   -- 【时间窗待确认】全 SQL 只改这一处
      and live_hours_only_live > 0                    -- 当天真的开播
),

-- 收敛到目标名单并汇总到「主播 x 日」：join 条件只保留业务关联键 luid
anchor_day as (
    select
        r.dt,
        r.luid,
        max(r.nickname) as nickname,
        sum(r.live_hours_only_live) as live_hours
    from anchor_day_raw r
    inner join target_anchor t
        on r.luid = t.luid
    group by
        r.dt,
        r.luid
)

-- 主查询：每个主播 by 天的开播时长
select
    a.dt as "日期",
    a.luid as "主播uid",
    a.nickname as "主播昵称",
    round(a.live_hours, 4) as "当日开播时长(小时)",
    round(a.live_hours * 60, 1) as "当日开播时长(分钟)"
from anchor_day a
order by
    a.luid,
    a.dt;

